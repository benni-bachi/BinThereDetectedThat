'use strict';
const assert=require('node:assert/strict');
const {validCredentials,createSession}=require('../demo-login.js');
assert(validCredentials('admin','admin'));
assert(validCredentials(' admin ','admin'));
for (const pair of [['admin','wrong'],['Admin','admin'],['admin','Admin'],['','admin'],['admin',''],[null,'admin']]) assert(!validCredentials(...pair));
const values=new Map();
const storage={getItem:key=>values.get(key),setItem:(key,value)=>values.set(key,value),removeItem:key=>values.delete(key)};
const session=createSession(storage);
assert(!session.isSignedIn());
assert(!session.signIn('admin','wrong'));
assert.equal(values.size,0);
assert(session.signIn('admin','admin'));
assert(session.isSignedIn());
assert(createSession(storage).isSignedIn());
assert(![...values.values()].includes('admin'));
session.signOut();
assert(!session.isSignedIn());
assert(!createSession(storage).isSignedIn());
assert.equal(values.size,0);
const unavailable={getItem(){throw Error('Storage unavailable');},setItem(){throw Error('Storage unavailable');},removeItem(){throw Error('Storage unavailable');}};
const memory=createSession(unavailable);
assert(memory.signIn('admin','admin'));
assert(memory.isSignedIn());
memory.signOut();assert(!memory.isSignedIn());
assert(!createSession(unavailable).isSignedIn());
console.log('Demo sign-in checks passed: credentials, tab session, sign-out, and unavailable storage.');
